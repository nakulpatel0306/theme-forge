import { hexToRgb } from '../core/color'
import { ansi, derived } from '../core/palette'
import type { Target } from './types'

function color(name: string, hex: string): string {
  const { r, g, b } = hexToRgb(hex)
  const component = (v: number) => (v / 255).toFixed(6)
  return `  <key>${name}</key>
  <dict>
    <key>Alpha Component</key>
    <real>1</real>
    <key>Blue Component</key>
    <real>${component(b)}</real>
    <key>Color Space</key>
    <string>sRGB</string>
    <key>Green Component</key>
    <real>${component(g)}</real>
    <key>Red Component</key>
    <real>${component(r)}</real>
  </dict>`
}

export const iterm2: Target = {
  id: 'iterm2',
  name: 'iTerm2',
  kind: 'terminal',
  // iTerm2 imports color presets from anywhere, so this just needs a home
  path: (slug) => `.config/theme-forge/${slug}.itermcolors`,
  setup: () => 'Double-click the file, then pick it under Settings > Profiles > Colors > Color Presets',
  render(palette) {
    const { colors: c } = palette
    const d = derived(palette)
    const { normal, bright } = ansi(palette)
    const entries = [
      ...[...normal, ...bright].map((hex, i) => color(`Ansi ${i} Color`, hex)),
      color('Background Color', c.bg),
      color('Foreground Color', c.fg),
      color('Bold Color', c.fg),
      color('Cursor Color', d.cursor),
      color('Cursor Text Color', c.bg),
      color('Selection Color', d.selection),
      color('Selected Text Color', c.fg),
      color('Link Color', c.blue),
      color('Badge Color', c.blue),
      color('Tab Color', c.surface),
    ]
    return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- ${palette.name.replace(/--/g, '-')}, generated by theme-forge -->
<plist version="1.0">
<dict>
${entries.join('\n')}
</dict>
</plist>
`
  },
}
