import type { Palette } from '../core/palette'

export type Target = {
  id: string
  name: string
  kind: 'terminal' | 'editor' | 'tool'
  // Where the file goes, relative to $HOME. Always a standalone theme file,
  // never the tool's main config, so applying a theme can't clobber settings.
  path: (slug: string) => string
  // The one line the user adds to their own config to switch the theme on
  setup: (slug: string) => string
  render: (palette: Palette, slug: string) => string
}

export const header = (palette: Palette, comment = '#') =>
  `${comment} ${palette.name}, generated by theme-forge\n`
