import { derived } from '../core/palette'
import { tokenRules, type TokenRule } from './textmate'
import type { Target } from './types'

const escape = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

function dict(entries: Record<string, string>, indent: string): string {
  return Object.entries(entries)
    .map(([k, v]) => `${indent}<key>${k}</key>\n${indent}<string>${escape(v)}</string>`)
    .join('\n')
}

function rule({ name, scope, foreground, fontStyle }: TokenRule): string {
  const settings: Record<string, string> = { foreground }
  if (fontStyle !== undefined) settings.fontStyle = fontStyle
  return `    <dict>
      <key>name</key>
      <string>${escape(name)}</string>
      <key>scope</key>
      <string>${escape(scope.join(', '))}</string>
      <key>settings</key>
      <dict>
${dict(settings, '        ')}
      </dict>
    </dict>`
}

export const bat: Target = {
  id: 'bat',
  name: 'bat',
  kind: 'tool',
  path: (slug) => `.config/bat/themes/${slug}.tmTheme`,
  setup: (slug) => `Run \`bat cache --build\`, then set \`--theme="${slug}"\` in ~/.config/bat/config`,
  render(palette) {
    const { colors: c } = palette
    const d = derived(palette)
    const base = {
      background: c.bg,
      foreground: c.fg,
      caret: d.cursor,
      lineHighlight: d.lineHighlight,
      selection: d.selection,
      gutter: c.bg,
      gutterForeground: c.muted,
    }
    return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- ${escape(palette.name)}, generated by theme-forge -->
<plist version="1.0">
<dict>
  <key>name</key>
  <string>${escape(palette.name)}</string>
  <key>settings</key>
  <array>
    <dict>
      <key>settings</key>
      <dict>
${dict(base, '        ')}
      </dict>
    </dict>
${tokenRules(palette).map(rule).join('\n')}
  </array>
</dict>
</plist>
`
  },
}
